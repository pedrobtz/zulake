source("setup.R")
root <- file.path(fixture_dir(), "tables")
U <- "abfss://lake@acct.dfs.core.windows.net/zl-basic"
run <- function(label, override, expr = quote(lake_read(lake_open(U, credentials = cred))), ...) {
  log <- new.env(); use(azure_fake(root, log, override = override, max_requests = 200L, ...))
  w <- list()
  e <- withCallingHandlers(try_(eval(expr)), warning = function(x) { w[[length(w) + 1]] <<- x; invokeRestart("muffleWarning") })
  cat("==", label, ": requests", length(log$requests), "\n"); show(e)
  if (inherits(e, "condition")) { f <- unclass(e); f$message <- NULL; cat("   fields:", paste(names(f), vapply(f, function(v) paste(format(v), collapse = ","), ""), sep = "=", collapse = "; "), "\n") }
  if (length(w)) cat("   warnings:", vapply(w, conditionMessage, ""), "\n")
  cat("   token leak:", has_token(e), any(vapply(w, has_token, NA)), "\n")
  hosts <- vapply(log$requests, function(r) paste(sub("^https?://([^/]+)/.*", "\\1", r$url), !is.null(r$headers$authorization)), "")
  print(table(hosts))
  invisible(list(e = e, log = log))
}
R <- zuhttp::zu_response
is_list <- function(r) identical(r$query$comp, "list")
is_data <- function(r) grepl("parquet$", r$path)
is_commit <- function(r) grepl("json$", r$path)
run("302 redirect to evil host on list", function(r) if (is_list(r) && grepl("acct", r$url)) R(302L, c(Location = "https://evil.example/lake?x=1")))
run("307 redirect on data file to other host", function(r) if (is_data(r) && grepl("acct.blob", r$url)) R(307L, c(Location = sub("acct", "other", r$url))))
run("307 redirect same host on data", local({k <- 0; function(r) if (is_data(r) && (k <<- k + 1) == 1) R(307L, c(Location = r$url))}))
run("500 on list", function(r) if (is_list(r)) R(500L, c(`x-ms-error-code` = "InternalError")))
run("503 once on list", local({k <- 0; function(r) if (is_list(r) && (k <<- k + 1) == 1) R(503L, c(`x-ms-error-code` = "ServerBusy", `Retry-After` = "0"))}))
run("429 on commit", function(r) if (is_commit(r)) R(429L, c(`Retry-After` = "0")))
