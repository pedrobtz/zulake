source("setup.R")
root <- file.path(fixture_dir(), "tables")
U <- "abfss://lake@acct.dfs.core.windows.net/zl-basic"
nreq <- function(log) length(log$requests)
reg <- function() length(ls(zulake:::credential_env))
log <- new.env(); use(azure_fake(root, log))
ncred <- 0; cr <- local({ secret <- TOKEN; function() { ncred <<- ncred + 1; secret } })
t <- lake_open(U, credentials = cr)
ref <- lake_read(t)
cat("== snapshot fields:", names(unclass(t)), "\n")
cat("token in snapshot:", has_token(t), " in print:", grepl("SECRET", paste(capture.output(print(t)), collapse = "")), " in str:", any(grepl("SECRET", capture.output(str(t)))), "\n")
cat("token in format/summary:", any(grepl("SECRET", c(capture.output(summary(t)), capture.output(format(t))))), "\n")
cat("token in options:", has_token(options()), " in client option:", has_token(getOption("zulake.azure_client")), "\n")
cat("serialize size:", length(serialize(t, NULL)), "\n")
cat("== cache: second read sends no data requests\n")
n0 <- nreq(log); x <- lake_read(t); cat("requests for 2nd read:", nreq(log) - n0, "\n")
cat("== lake_load shares cache and credentials\n")
t2 <- lake_load(t, version = 1); n0 <- nreq(log); x <- lake_read(t2); cat("v1 read requests:", nreq(log) - n0, " cred calls:", ncred, "\n")
t3 <- lake_load(t); n0 <- nreq(log); x3 <- lake_read(t3); cat("lake_load(t) latest read requests:", nreq(log) - n0, " same:", identical(x3, ref), " shared env:", identical(t3$downloads, t$downloads), "\n")
cat("== second lake_open downloads again\n")
tb <- lake_open(U, credentials = cr); n0 <- nreq(log); x <- lake_read(tb); cat("requests:", nreq(log) - n0, " cred calls:", ncred, " registry:", reg(), "\n")
cat("== RDS same session\n")
f <- file.path(getwd(), "snap.rds"); saveRDS(t, f); cat("token in rds file:", length(grepRaw("SECRETto", readBin(f, "raw", file.size(f)), fixed = TRUE)) > 0, "\n")
saveRDS(t, "snap_ascii.rds", ascii = TRUE, compress = FALSE); cat("token in ascii rds:", any(grepl("SECRETto", readLines("snap_ascii.rds"))), "\n")
c1 <- readRDS(f); n0 <- nreq(log); r <- try_(lake_read(c1)); cat("copy read ok:", identical(r, ref), " requests:", nreq(log) - n0, "(cache paths restored)\n")
cat("== derived snapshot after original gc\n")
rm(t, t3, tb, x, x3); invisible(gc()); cat("registry after rm t (t2 alive):", reg(), "\n")
r <- try_(lake_read(t2)); cat("t2 read ok:", is.data.frame(r), "\n")
r <- try_(lake_read(c1)); cat("copy while t2 alive:", is.data.frame(r), "\n")
r <- try_(lake_load(c1)); cat("copy lake_load while t2 alive:", class(r)[1], "\n")
rm(t2, r); invisible(gc()); invisible(gc()); cat("registry after rm t2:", reg(), "\n")
n0 <- nreq(log); r <- try_(lake_read(c1)); cat("copy read after originals gone (cached files exist): "); if (is.data.frame(r)) cat("OK rows", nrow(r), "requests", nreq(log) - n0, "\n") else show(r)
r <- try_(lake_load(c1)); show(r); cat("  requests:", nreq(log) - n0, "\n")
r <- try_(lake_read(lake_load(c1, version = 4))); show(r)
r <- try_(lake_files(c1)); cat("lake_files on copy:", class(r)[1], "\n")
cat("== dropping a restored copy does not remove an entry\n")
t <- lake_open(U, credentials = cr); c2 <- unserialize(serialize(t, NULL)); rm(c2); invisible(gc()); cat("registry:", reg(), " t still works:", is.data.frame(try_(lake_read(lake_load(t)))), "\n")
cat("== copy made by modifying snapshot (handle shared)\n")
t$foo <- 1; rm(t); invisible(gc()); cat("registry:", reg(), "\n")
