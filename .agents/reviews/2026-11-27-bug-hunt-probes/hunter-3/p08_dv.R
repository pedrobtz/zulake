run <- function(label, override, expr = quote(lake_read(lake_open(U, credentials = cred)))) {
  log <- new.env(); use(azure_fake(root, log, override = override, max_requests = 100L))
  e <- try_(eval(expr)); cat("==", label, ": requests", length(log$requests), "\n")
  if (is.data.frame(e)) cat("  rows", nrow(e), "same as local:", identical(e, ref), "\n") else show(e)
  dvr <- Filter(is_dv, log$requests)
  cat("  dv requests:", paste(vapply(dvr, function(r) paste(r$method, r$headers$range %||% ""), ""), collapse = " | "), " leak:", has_token(e), "\n")
  invisible(e)
}
