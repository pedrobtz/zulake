source(file.path(Sys.getenv("W"), "common.R"))
cat("locale:", Sys.getlocale("LC_CTYPE"), "\n")
e_utf8 <- rawToChar(as.raw(c(0xc3, 0xa9))); Encoding(e_utf8) <- "UTF-8"
e_nat <- rawToChar(as.raw(c(0xc3, 0xa9)))
tbl <- lake_open(file.path(W, "t/types"))
full <- lake_read(tbl, columns = c("s", "a"))
cat("col encodings:", Encoding(full$s), "\n")
cat("base R  s == utf8-marked:", full$a[full$s %in% e_utf8], " native:", full$a[which(full$s == e_nat)], "\n")
cat("zulake  s == utf8-marked:", lake_read(tbl, filter = s == e_utf8)$a, " native:", lake_read(tbl, filter = s == e_nat)$a, "\n")
cat("zulake files utf8:", nrow(lake_files(tbl, filter = s == e_utf8)), " native:", nrow(lake_files(tbl, filter = s == e_nat)), "\n")
cat("zulake s < utf8:", lake_read(tbl, filter = s < e_utf8)$a, "| s > 'a':", lake_read(tbl, filter = s > "a")$a, "\n")
cat("zulake s %in% utf8:", lake_read(tbl, filter = s %in% c("Z", e_utf8))$a, "\n")
lat <- "\xe9"; Encoding(lat) <- "latin1"
cat("zulake s == latin1:", lake_read(tbl, filter = s == lat)$a, " base:", full$a[which(full$s == lat)], "\n")
cat("row-wise startsWith utf8:", try1(lake_read(tbl, filter = startsWith(s, e_utf8)))$a, "\n")
